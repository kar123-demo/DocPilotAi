const SAVED_REPORT_KEY = "docpilot:last-report";

function readSavedReport() {
  try {
    const saved = localStorage.getItem(SAVED_REPORT_KEY);
    const parsed = saved ? JSON.parse(saved) : null;
    return parsed?.report_id ? parsed : null;
  } catch {
    return null;
  }
}

const slug = (title) =>
  title
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/(^-|-$)/g, "");

