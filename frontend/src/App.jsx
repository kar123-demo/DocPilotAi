export default function App() {
  const chatParams = new URLSearchParams(window.location.search);
  const chatProjectId = chatParams.get("chatProject");
  const chatProjectName = chatParams.get("projectName") || "Project";
  const [status, setStatus] = useState(null);
  const [report, setReport] = useState(null);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState("");
  const [form, setForm] = useState({
    repository_url: "",
    project_name: "",
  });

  useEffect(() => {
    if (chatProjectId) return undefined;
    getStatus()
      .then(setStatus)
      .catch(() => setStatus({ llm_configured: false }));
    return undefined;
  }, [chatProjectId]);

  const submit = async (event) => {
    event.preventDefault();
    setBusy(true);
    setError("");
    try {
      setReport(
        await analyzeRepository({
          ...form,
          project_name: form.project_name || null,
        }),
      );
    } catch (err) {
      setError(err.message);
    } finally {
      setBusy(false);
    }
  };

  if (chatProjectId) {
    return <ChatWidget reportId={chatProjectId} projectName={chatProjectName} standalone />;
  }

  if (report) {
    return <ReportView report={report} onNewReport={() => setReport(null)} />;
  }

  return (
    <Landing status={status} form={form} setForm={setForm} submit={submit} busy={busy} error={error} />
  );
}
