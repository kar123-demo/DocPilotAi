export default function App() {
  const chatParams = new URLSearchParams(window.location.search);
  const chatProjectId = chatParams.get("chatProject");
  const chatProjectName = chatParams.get("projectName") || "Project";
  const [status, setStatus] = useState(null);
  const [report, setReport] = useState(readSavedReport);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState("");
  const [projects, setProjects] = useState([]);
  const [showProjects, setShowProjects] = useState(false);
  const [projectsLoading, setProjectsLoading] = useState(false);
  const [projectsError, setProjectsError] = useState("");
  const [savingProject, setSavingProject] = useState(false);
  const [saveError, setSaveError] = useState("");
  const [form, setForm] = useState({
    repository_url: "",
    project_name: "",
  });

  useEffect(() => {
    if (chatProjectId) return undefined;
    getStatus()
      .then(setStatus)
      .catch(() => setStatus({ llm_configured: false }));
    getSavedProjects().then(setProjects).catch(() => setProjects([]));
    return undefined;
  }, [chatProjectId]);

  useEffect(() => {
    try {
      if (report) localStorage.setItem(SAVED_REPORT_KEY, JSON.stringify(report));
      else localStorage.removeItem(SAVED_REPORT_KEY);
    } catch {
      // Keep the report usable in memory if browser storage is unavailable/full.
    }
  }, [report]);

  const refreshProjects = async () => {
    setProjectsLoading(true);
    setProjectsError("");
    try {
      setProjects(await getSavedProjects());
    } catch (err) {
      setProjectsError(err.message);
    } finally {
      setProjectsLoading(false);
    }
  };

  useEffect(() => {
    if (!showProjects) return undefined;
    const timer = window.setInterval(() => { void refreshProjects(); }, 60_000);
    return () => window.clearInterval(timer);
  }, [showProjects]);

  const openSavedProject = async (projectId) => {
    setProjectsLoading(true);
    setProjectsError("");
    try {
      setReport(await getSavedReport(projectId));
      setShowProjects(false);
    } catch (err) {
      setProjectsError(err.message);
    } finally {
      setProjectsLoading(false);
    }
  };

  const removeSavedProject = async (project) => {
    if (!window.confirm(`Delete “${project.project_name}”? Its saved report, generated files, repository copy, and search index will be removed.`)) return;
    setProjectsLoading(true);
    setProjectsError("");
    try {
      await deleteSavedProject(project.report_id);
      setProjects((current) => current.filter((item) => item.report_id !== project.report_id));
    } catch (err) {
      setProjectsError(err.message);
    } finally {
      setProjectsLoading(false);
    }
  };

  const saveCurrentProject = async () => {
    if (!report) return;
    setSavingProject(true);
    setSaveError("");
    try {
      await saveProject(report);
      await refreshProjects();
    } catch (err) {
      setSaveError(err.message);
    } finally {
      setSavingProject(false);
    }
  };

  const submit = async (event) => {
    event.preventDefault();
    setBusy(true);
    setError("");
    try {
      setReport(
        await analyzeRepository({
          ...form,
          project_name: form.project_name || null,
        }),
      );
    } catch (err) {
      setError(err.message);
    } finally {
      setBusy(false);
    }
  };

  if (chatProjectId) {
    return <ChatWidget reportId={chatProjectId} projectName={chatProjectName} standalone />;
  }

  if (report) {
    return (
      <ReportView
        report={report}
        onNewReport={() => setReport(null)}
        onSaveProject={saveCurrentProject}
        projectSaved={projects.some((project) => project.report_id === report.report_id)}
        savingProject={savingProject}
        saveError={saveError}
      />
    );
  }

  return (
    <Landing
      status={status}
      form={form}
      setForm={setForm}
      submit={submit}
      busy={busy}
      error={error}
      onViewProjects={() => { setShowProjects(true); void refreshProjects(); }}
      showProjects={showProjects}
      projects={projects}
      projectsLoading={projectsLoading}
      projectsError={projectsError}
      onOpenProject={openSavedProject}
      onDeleteProject={removeSavedProject}
      onCloseProjects={() => setShowProjects(false)}
    />
  );
}
